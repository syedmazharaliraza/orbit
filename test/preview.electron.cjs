const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { join } = require('node:path')
const { writeFile } = require('node:fs/promises')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 630, height: 388, show: false, transparent: true, frame: false,
    webPreferences: { preload: join(__dirname, 'preview.preload.cjs'), contextIsolation: false, sandbox: false, backgroundThrottling: false } })
  win.webContents.on('console-message', event => { if (event.level === 'error') console.error('[renderer]', event.message) })
  win.webContents.on('preload-error', (_event, path, error) => console.error('Preload failed', path, error))
  const run = async source => {
    try { return await win.webContents.executeJavaScript(source) }
    catch (error) { console.error('Failed check:', source); throw error }
  }
  try {
    await win.loadFile(join(__dirname, '../out/renderer/index.html'))
    await delay(150)
    await run(`document.querySelector('.crew-pod__open').click()`)
    await delay(50)
    await run(`document.querySelector('.orbit-worker').dispatchEvent(new PointerEvent('pointermove', { bubbles: true }))`)
    await delay(300)
    assert.equal(await run(`document.querySelector('.preview-state').textContent`), 'Working')
    assert.equal(await run(`document.querySelector('.preview-context p').textContent`), 'src/booking/bookingDate.ts')
    assert.equal(await run(`document.querySelectorAll('.hover-preview button, .worker-detail, textarea').length`), 0)
    await writeFile(join(__dirname, '../.build/preview-working.png'), (await win.webContents.capturePage()).toPNG())
    await run(`window.previewTest.update({ action: 'Editing bookingDate.ts' })`)
    await delay(80)
    const motion = await run(`Array.from(document.querySelectorAll('.activity-ticker__line')).map(el => ({ text: el.textContent, opacity: Number(getComputedStyle(el).opacity), y: new DOMMatrix(getComputedStyle(el).transform).m42 }))`)
    assert.equal(motion.length, 2)
    assert.ok(motion[0].y < 0 && motion[1].y > 0, 'old status leaves upward; new status enters below')
    assert.ok(motion.every(line => line.opacity < 1), 'only a settled status is fully opaque')
    await run(`window.previewTest.update({ action: 'Running tests' })`)
    await delay(850)
    assert.equal(await run(`document.querySelector('.activity-ticker__line').textContent`), 'Running tests')
    assert.equal(await run(`document.querySelectorAll('.activity-ticker__line').length`), 1)
    await run(`window.previewTest.update({ state: 'waiting', presentation: 'waiting', permission: true, action: 'Run the migration against the local booking database?', context: { label: 'Requested action', text: 'pnpm db:migrate --database booking_local', code: true } })`)
    await delay(500)
    assert.equal(await run(`document.querySelector('.preview-state').textContent`), 'Needs you')
    const bounds = await run(`(() => { const r = document.querySelector('.hover-preview').getBoundingClientRect(); return { bottom: r.bottom, right: r.right, width: r.width } })()`)
    assert.ok(bounds.bottom < 388 && bounds.right < 300, 'expanded preview fits beside the orbit')
    await writeFile(join(__dirname, '../.build/preview-permission.png'), (await win.webContents.capturePage()).toPNG())
    await run(`window.previewTest.update({ permission: false, question: true, action: 'What would you like to work on today?', context: { label: 'Choices', choices: ['Continue current work', 'Review changes', 'Commit & clean up', 'Explore & explain'], remaining: 0 } })`)
    await delay(500)
    await writeFile(join(__dirname, '../.build/preview-question.png'), (await win.webContents.capturePage()).toPNG())
    await run(`window.previewTest.failOpen = true; document.querySelector('.orbit-worker').click()`)
    await delay(50)
    assert.equal(await run(`document.querySelector('.observation-bar').textContent`), 'Session unavailable')
    await run(`window.previewTest.failOpen = false; document.querySelector('.orbit-worker').click()`)
    await delay(50)
    assert.deepEqual(await run(`window.previewTest.opened`), ['preview-session', 'preview-session'])
    assert.equal(await run(`window.previewTest.modes.at(-1)`), 'collapsed')
    assert.equal(await run(`window.previewTest.modes.includes('detail')`), false)
    await win.webContents.debugger.attach('1.3')
    await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
    await run(`document.querySelector('.crew-pod__open').click()`)
    await delay(50)
    await run(`document.querySelector('.orbit-worker').dispatchEvent(new PointerEvent('pointermove', { bubbles: true }))`)
    await delay(50)
    await run(`window.previewTest.update({ action: 'Refactor finished', state: 'done', presentation: 'done', question: false, context: undefined })`)
    await delay(50)
    assert.equal(await run(`document.querySelectorAll('.activity-ticker__line').length`), 1)
    assert.equal(await run(`document.querySelector('.activity-ticker__line').textContent`), 'Refactor finished')
    assert.equal(await run(`document.querySelector('.preview-state').textContent`), 'Completed')
    win.webContents.debugger.detach()
    console.log('Preview rendering, ticker motion, reduced motion, context, and session click tests passed')
  } finally { win.destroy() }
}).then(() => app.exit(0), error => { console.error(error); app.exit(1) })
